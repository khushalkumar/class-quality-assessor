"""Render a report dict as Markdown (for download)."""
from __future__ import annotations

from .rubric import DIMENSIONS


def to_markdown(rep: dict) -> str:
    a, m = rep["assessment"], rep["metrics"]["transcript"]
    names = {d["key"]: d["name"] for d in DIMENSIONS}
    L = [f"# Class quality report: **{rep['rating']}**", "",
         f"Weighted rubric score **{rep['weighted_score']:.2f} / 5** · confidence **{rep['confidence']}** · "
         f"model's holistic view: {rep['holistic_rating']}", "",
         f"_{a['class_summary']}_", ""]
    if rep.get("needs_review"):
        L += ["> **Needs human review**", *[f"> - {r}" for r in rep.get("review_reasons", [])], ""]
    if rep.get("missing_signals"):
        L += [f"_Signals not available for this class: {', '.join(rep['missing_signals'])}._", ""]
    L += ["## Verdict", a["verdict"], ""]
    if a.get("red_flags"):
        L += ["## Red flags", *[f"- **{x['severity']}** `{x['timestamp']}` {x['issue']}" for x in a["red_flags"]], ""]
    if rep.get("capped_by_red_flag"):
        L += ["_Rating capped because of a major red flag._", ""]
    L += ["## Rubric scores", "| Dimension | Score | Why |", "|---|---|---|"]
    for d in a["dimensions"]:
        L.append(f"| {names.get(d['key'], d['key'])} | {d['score']}/5 | {d['summary']} |")
    L += ["", "## Evidence"]
    for d in a["dimensions"]:
        L.append(f"**{names.get(d['key'], d['key'])}**")
        L += [f"- `{e['timestamp']}` {e['observation']} — “{e['quote']}”"
              + (" _(quote verified)_" if e.get("quote_status") in ("exact", "approximate") else "")
              for e in d["evidence"]]
        L.append("")
    L += ["## Strengths", *[f"- **{p['title']}** (`{p['timestamp']}`): {p['detail']}" for p in a["strengths"]], "",
          "## Areas to improve & coaching tips"]
    for p in a["improvements"]:
        L += [f"- **{p['title']}** (`{p['timestamp']}`): {p['detail']}", f"  - Tip: {p['coaching_tip']}"]
    v = a["visual"]
    L += ["", "## Setup check (from video frames)",
          f"- Camera on: {v['teacher_camera_on']} · face visible: {v['teacher_face_visible']} · background: "
          f"{v['branded_background']} · lighting: {v['lighting']} · screen share: {'yes' if v['screen_share_used'] else 'no'}",
          f"- {v['notes']}", "", "## Objective metrics"]
    for k, val in m.items():
        if not isinstance(val, list):
            L.append(f"- {k.replace('_', ' ')}: {val}")
    v = rep.get("versions", {})
    L += ["", f"_Generated by class-quality-assessor · pipeline {v.get('pipeline', '?')} · prompt "
              f"{rep['prompt_version']} · rubric {v.get('rubric', '?')} · {rep['model']} · "
              f"transcript source: {rep['transcript_source']} · job {rep.get('job', {}).get('id', '-')}_"]
    return "\n".join(L)
